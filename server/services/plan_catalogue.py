"""Data-driven subscription plan catalogue for OpenMynd.

The internal tier keys stay stable for entitlements and Stripe metadata. Public names,
prices, copy, and quotas are read from this table so an administrator can adjust the
matrix without code changes.
"""

from __future__ import annotations

