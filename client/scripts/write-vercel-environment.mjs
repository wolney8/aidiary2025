import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(__dirname, "../src/environments/environment.hosted.ts");

const apiBaseUrl = (process.env.OPENMYND_API_BASE_URL || "/api").trim();
const apiFallbackBaseUrl = (process.env.OPENMYND_API_FALLBACK_BASE_URL || apiBaseUrl).trim();
const cookieOnlyAuth = /^true$/i.test(process.env.OPENMYND_COOKIE_ONLY_AUTH || "false");
const inactivityTimeoutSeconds = Number.parseInt(
  process.env.OPENMYND_INACTIVITY_TIMEOUT_SECONDS || "900",
  10,
);
const inactivityWarningSeconds = Number.parseInt(
  process.env.OPENMYND_INACTIVITY_WARNING_SECONDS || "60",
  10,
);

const serialised = `// Generated by scripts/write-vercel-environment.mjs during hosted builds.
export const environment = {
  production: true,
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
  apiFallbackBaseUrl: ${JSON.stringify(apiFallbackBaseUrl)},
  cookieOnlyAuth: ${cookieOnlyAuth},
  inactivity: {
    enabled: true,
    timeoutSeconds: ${Number.isFinite(inactivityTimeoutSeconds) ? inactivityTimeoutSeconds : 900},
    warningSeconds: ${Number.isFinite(inactivityWarningSeconds) ? inactivityWarningSeconds : 60},
  },
};
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, serialised, "utf8");
console.log(`Wrote Angular production environment for ${apiBaseUrl}`);
